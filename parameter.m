function para = parameter()
%% ==========================================================
% 文件名：parameter.m
% 功能：连续LFM无线电引信参数
% MATLAB R2024b
% ==========================================================

%% 基本常数
para.c = 3e8;                         % 光速 (m/s)

%% 载频
para.fc = 10e9;                       % 载频 10 GHz
para.lambda = para.c / para.fc;       % 波长

%% ==========================================================
% 连续LFM参数
% ==========================================================

para.B = 20e6;                        % 扫频带宽 20 MHz

para.Tsweep = 100e-6;                 % 一次完整扫频时间 100 us

para.fs = 80e6;                       % 采样率 80 MHz

%% 起始频率
% 这里采用复基带模型，因此起始频率设为 -B/2
para.fStart = -para.B/2;

%% 终止频率
para.fStop = para.B/2;

%% 调频斜率
para.K = para.B / para.Tsweep;

%% ==========================================================
% 仿真观测时间
% ==========================================================

para.Tobs = 100e-6;

para.N = round(para.Tobs * para.fs);

para.t = (0:para.N-1)' / para.fs;

%% ==========================================================
% 目标参数
% ==========================================================

para.R = 50;                          % 目标距离 50 m

para.v = 30;                          % 目标速度 30 m/s

para.A = 1;                           % 回波幅度

%% ==========================================================
% 目标传播参数
% ==========================================================

para.tau = 2 * para.R / para.c;

para.fd = 2 * para.v / para.lambda;

%% ==========================================================
% 噪声
% ==========================================================

para.SNR = 20;

end